/**
 * `skill_state`: the one write the model performs itself, and the `⊕` operator in
 * practice.
 *
 * The tool is the model's only channel into Σ, and it is deliberately narrow: a patch,
 * a step, a one-line note. Everything about *whether* a patch is well formed lives in
 * the deterministic runtime — keys the schema does not own are dropped, a `null` deletes,
 * arrays replace wholesale — because the paper's own failure modes are a state that was
 * emptied or overwritten by a malformed write. The model is trusted with what it knows
 * and not with what the schema is.
 *
 * No reply to the user is generated by a state write: the tool returns an
 * acknowledgement to the model and nothing else, so a bookkeeping call never costs the
 * user a turn of its own.
 *
 * @module opencode-skill-state/tool
 */

import { ackText, toolDescription } from "./prompts.ts"
import { isPlainObject, render, STATE_KEYS, unknownKeys } from "./schema.ts"
import { estimateTokens } from "./context.ts"
import { stateStore } from "./state.ts"
import type { StorageDomain, ToolCallContext, ToolDefinition, ToolResult } from "./types.ts"

/** The tool's name, which is also what the standing policy tells the model to call. */
export const TOOL_NAME = "skill_state"

/**
 * The parameter contract of `skill_state`, as plain JSON Schema.
 *
 * `state_patch` is the whole channel: a JSON object of the keys being written, where a
 * `null` value is an instruction to delete rather than a value to store.
 */
export const TOOL_INPUT = {
  type: "object",
  additionalProperties: false,
  properties: {
    state_patch: {
      type: "object",
      description:
        "The keys to write, merged over the current state. Dictionaries merge key by key, arrays replace wholesale, and a null value deletes the key. Keys outside the schema are dropped.",
    },
    step: {
      type: "integer",
      description: "The step index to set. When omitted, the runtime advances the counter by one.",
    },
    summary: {
      type: "string",
      description: "One line about what changed, carried alongside Σ and printed by /skillstate.",
    },
  },
}

/**
 * A tool result, as OpenCode's shape wants it.
 *
 * `output` needs a schema of its own or the host refuses the result — a result that
 * declares output without one comes back to the model as
 * `Tool result declared output without an output schema` and the call is lost.
 */
export function textResult(text: string, output: Record<string, unknown>): ToolResult {
  return { content: [{ type: "text", text }], output }
}

/** A session id, when the host handed the tool one. */
export function sessionIdOf(context: unknown): string | undefined {
  const id = (context as { sessionID?: unknown } | undefined)?.sessionID
  return typeof id === "string" && id.length > 0 ? id : undefined
}

/**
 * Build `skill_state`.
 *
 * @param options - the durable store, when the host has one, so a write outlives the
 *   process that made it.
 * @returns the tool definition, ready for `tool.transform`.
 */
export function createSkillState(options: { readonly storage?: StorageDomain } = {}): ToolDefinition {
  const storage = options.storage
  return {
    name: TOOL_NAME,
    description: toolDescription(),
    input: TOOL_INPUT,
    // Measured, and it is the difference between a callable tool and a decoration. A
    // registered tool is not an offered tool: the host's request carries the registry's
    // `codemode: false` entries, and everything else is reached through `execute`, the
    // code-mode wrapper, instead of by name.
    options: { codemode: false },
    // Permissive on purpose: the ack and the refusals share one shape only in being
    // objects, and the host refuses a result that carries `output` with no schema.
    output: { type: "object", additionalProperties: true },
    execute: async (args: any, context: ToolCallContext): Promise<ToolResult> => {
      const sessionID = sessionIdOf(context)
      if (sessionID === undefined) {
        return textResult(
          "skill_state needs a session: it records the state of the conversation it is called from.",
          { kind: "error" },
        )
      }
      const raw = args as { state_patch?: unknown; step?: unknown; summary?: unknown } | undefined
      const patch = raw?.state_patch
      if (patch !== undefined && !isPlainObject(patch)) {
        return textResult(
          "state_patch must be a JSON object of the keys you are setting; set a key to null to delete it.",
          { kind: "error" },
        )
      }
      const wanted = raw?.step
      if (wanted !== undefined && wanted !== null && !Number.isInteger(wanted)) {
        return textResult("step must be an integer, or left out entirely.", { kind: "error" })
      }
      if (raw?.summary !== undefined && typeof raw.summary !== "string") {
        return textResult("summary must be one line of text.", { kind: "error" })
      }

      const record = await stateStore(sessionID, { storage })
      // The step is part of the patch, not a side channel: it is a key of Σ like any
      // other, so it merges, it can be deleted, and it shows up in what changed. A write
      // with no `step` advances whatever Σ already carries — a seed or an earlier write.
      const step = wanted === undefined || wanted === null ? record.step() + 1 : (wanted as number)
      const written: Record<string, unknown> = isPlainObject(patch) ? { ...patch } : {}
      written["step"] = step
      const dropped = patch === undefined ? [] : unknownKeys(patch)

      const changed = await record.apply(written)
      if (typeof raw?.summary === "string") await record.setSummary(raw.summary)

      const output: Record<string, unknown> = {
        kind: "state",
        step,
        changed,
        dropped,
        keys: [...STATE_KEYS],
        summary: record.summary(),
        tokens: estimateTokens(render(record.get())),
      }
      return textResult(ackText({ step, changed, dropped }), output)
    },
  }
}
