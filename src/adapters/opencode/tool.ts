/**
 * `skill_state`: the definition envelope, as OpenCode's registry wants it.
 *
 * Everything about *whether* a patch is well formed lives in the host-free core
 * (`src/core/skill-state.ts`), because the `⊕` merge is a runtime decision and not a
 * host one. What is left here is only what OpenCode asks for around it: the
 * registration envelope the host reads, and the call that wraps the core's write into a
 * result the host will accept.
 *
 * The two measured details that earn this file its keep: a registered tool is not an
 * offered tool — the request carries the registry's `codemode: false` entries, so a tool
 * registered without one is reachable through `execute` but never by name; and a result
 * that declares `output` without a schema comes back to the model as
 * `Tool result declared output without an output schema` and the call is lost.
 *
 * No reply to the user is generated by a state write: the tool returns an acknowledgement
 * to the model and nothing else, so a bookkeeping call never costs the user a turn of its
 * own.
 *
 * @module mega-skillstate/adapters/opencode/tool
 */

import {
  TOOL_INPUT,
  TOOL_NAME,
  TOOL_OUTPUT,
  sessionIdOf,
  skillStateDescription,
  textResult,
  writeSkillState,
  type SkillStateWrite,
} from "../../core/skill-state.ts"
import type { StorageDomain, ToolCallContext, ToolDefinition, ToolResult } from "./types.ts"

// Re-exported so the names this adapter has always answered for still resolve from the
// page the feature map points at, even though the definitions now live in the core.
export {
  TOOL_INPUT,
  TOOL_NAME,
  TOOL_OUTPUT,
  describe,
  parsePatch,
  sessionIdOf,
  textResult,
  unfence,
} from "../../core/skill-state.ts"

/**
 * Build `skill_state`.
 *
 * @param options - the durable store, when the host has one, so a write outlives the
 *   process that made it.
 * @returns the tool definition, ready for `tool.transform`.
 */
export function createSkillState(options: { readonly storage?: StorageDomain } = {}): ToolDefinition {
  const storage = options.storage
  return {
    name: TOOL_NAME,
    description: skillStateDescription(),
    input: TOOL_INPUT,
    // Measured, and it is the difference between a callable tool and a decoration. A
    // registered tool is not an offered tool: the host's request carries the registry's
    // `codemode: false` entries, and everything else is reached through `execute`, the
    // code-mode wrapper, instead of by name.
    options: { codemode: false },
    // Permissive on purpose: the ack and the refusals share one shape only in being
    // objects, and the host refuses a result that carries `output` with no schema.
    output: TOOL_OUTPUT,
    execute: async (args: any, context: ToolCallContext): Promise<ToolResult> => {
      // The whole of the decision — parse, validate, merge, persist, acknowledge — is one
      // core call. This line is the host's only contribution: where the session id lives,
      // and which fields of the call are the model's to write.
      const raw = args as { state_patch?: unknown; step?: unknown; summary?: unknown } | undefined
      const write: SkillStateWrite = {
        sessionID: sessionIdOf(context),
        state_patch: raw?.state_patch,
        step: raw?.step,
        summary: raw?.summary,
      }
      const outcome = await writeSkillState(write, { storage })
      return textResult(outcome.text, outcome.output)
    },
  }
}
