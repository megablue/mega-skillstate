/**
 * `skill_state`'s semantics: the one write the model performs itself, and the `⊕`
 * operator in practice.
 *
 * The tool is the model's only channel into Σ, and it is deliberately narrow: a patch,
 * a step, a one-line note. Everything about *whether* a patch is well formed lives in
 * the deterministic runtime — keys the schema does not own are dropped, a `null` deletes,
 * arrays replace wholesale — because the paper's own failure modes are a state that was
 * emptied or overwritten by a malformed write. The model is trusted with what it knows
 * and not with what the schema is.
 *
 * No reply to the user is generated by a state write: the call returns an acknowledgement
 * to the model and nothing else, so a bookkeeping call never costs the user a turn of its
 * own.
 *
 * What lives here is the decision; the envelope around it — the parameter schema the
 * host validates against, the output schema, the registration options — is the host's and
 * stays in each adapter. `writeSkillState` takes plain values and returns plain values, so
 * OpenCode's `execute(args, ctx)` and Pi's `execute(toolCallId, params, signal, onUpdate,
 * ctx)` are both thin wrappers over the same call.
 *
 * @module mega-skillstate/skill-state
 */

import { ackText, toolDescription } from "./prompts.ts"
import { isPlainObject, render, STATE_KEYS, unknownKeys } from "./schema.ts"
import { condense, type CondenseReport } from "./sigma-condense.ts"
import { stateStore, type StateRecord } from "./state.ts"
import { estimateTokens } from "./context.ts"
import type { ResolvedConfig } from "./config.ts"
import type { StorageDomain } from "./types.ts"

/** The tool's name, which is also what the standing policy tells the model to call. */
export const TOOL_NAME = "skill_state"

/**
 * The parameter contract of `skill_state`, as plain JSON Schema.
 *
 * `state_patch` is the whole channel: a JSON object of the keys being written, where a
 * `null` value is an instruction to delete rather than a value to store. Its `type` is
 * a union rather than `"object"` alone on purpose — the host validates the call before
 * `execute` runs, so an object-only schema turns a quoted JSON string away at the door,
 * with nobody left to parse it. The union lets that call through to `parsePatch`.
 */
export const TOOL_INPUT = {
  type: "object",
  additionalProperties: false,
  properties: {
    state_patch: {
      type: ["object", "string"],
      description:
        "The keys to write, merged over the current state. Pass the object itself; a JSON string that encodes one is also accepted and parsed. Dictionaries merge key by key, arrays replace wholesale, and a null value deletes the key. Keys outside the schema are dropped.",
    },
    step: {
      type: "integer",
      description: "The step index to set. When omitted, the runtime advances the counter by one.",
    },
    summary: {
      type: "string",
      description: "One line about what changed, carried alongside Σ and printed by /skillstate.",
    },
  },
}

/** The output schema the tool result carries, when the host demands one. */
export const TOOL_OUTPUT = { type: "object", additionalProperties: true }

/** The tool's model-facing description. */
export function skillStateDescription(): string {
  return toolDescription()
}

/**
 * A tool result, as plain values.
 *
 * The `content` shape is the one both hosts accept — a list of text parts — and `output`
 * is the structured record a host hands to its renderers or its code-mode callers. Each
 * adapter wraps this into whatever its own envelope demands.
 */
export interface ToolResultValue {
  readonly content: ReadonlyArray<{ readonly type: "text"; readonly text: string }>
  readonly output: Record<string, unknown>
}

/** The result a write produces: what the model reads, and what a host records. */
export interface SkillStateOutcome {
  /** The text the model reads: the ack, or a refusal naming what arrived. */
  readonly text: string
  /** The structured record: `{kind, step, changed, dropped, …}` or `{kind: "error"}`. */
  readonly output: Record<string, unknown>
}

/** What one write carries. */
export interface SkillStateWrite {
  /** The session the write belongs to; without one there is nothing to write to. */
  readonly sessionID: string | undefined
  readonly state_patch?: unknown
  readonly step?: unknown
  readonly summary?: unknown
}

/** The text result, as a value both adapters can wrap. */
export function textResult(text: string, output: Record<string, unknown>): ToolResultValue {
  return { content: [{ type: "text", text }], output }
}

/** A session id, when the host handed the tool one. */
export function sessionIdOf(context: unknown): string | undefined {
  const id = (context as { sessionID?: unknown } | undefined)?.sessionID
  return typeof id === "string" && id.length > 0 ? id : undefined
}

/**
 * The patch the merge will apply, from either form the input schema lets through.
 *
 * The host validates a call before `execute` runs, so admitting the string form and
 * decoding it have to happen on opposite sides of that gate: the schema (a union)
 * admits, this function decodes. It unfences a Markdown code block first, because a
 * quoted payload tends to arrive fenced, and then requires what the merge requires — a
 * plain object. Anything else comes back as a soft error that names what arrived and
 * leaves Σ untouched.
 *
 * `fromString` is what the ack reports, so a transcript shows a quoted patch for what
 * it was: a payload the runtime had to decode, not the form to send next time.
 */
export function parsePatch(value: unknown): { patch?: Record<string, unknown>; error?: string; fromString: boolean } {
  if (value === undefined) return { fromString: false }
  if (isPlainObject(value)) return { patch: value, fromString: false }
  if (typeof value !== "string") {
    return {
      fromString: false,
      error:
        "state_patch must be a JSON object of the keys you are setting; set a key to null to delete it. It arrived as " +
        describe(value) +
        ".",
    }
  }
  let decoded: unknown
  try {
    decoded = JSON.parse(unfence(value).trim())
  } catch {
    return {
      fromString: true,
      error:
        "state_patch arrived as a string that is not valid JSON; nothing was written. Pass the object itself, not a quoted or fenced copy.",
    }
  }
  if (!isPlainObject(decoded)) {
    return {
      fromString: true,
      error: "state_patch decoded to " + describe(decoded) + ", not a JSON object of the keys you are setting; nothing was written.",
    }
  }
  return { patch: decoded, fromString: true }
}

/** The body of a string fenced as a Markdown code block, or the string as it stands. */
export function unfence(text: string): string {
  const fenced = /^\s*```[a-zA-Z]*\s*([\s\S]*?)\s*```\s*$/.exec(text)
  return fenced === null ? text : fenced[1]
}

/** What arrived, for a refusal: a JSON kind, not a JavaScript type name. */
export function describe(value: unknown): string {
  if (value === null) return "null"
  if (Array.isArray(value)) return "an array"
  return "a " + typeof value
}

/**
 * Fold Σ's long findings when this write has pushed it past the size line.
 *
 * The gate is the same threshold the report's size line uses, and that is the point
 * of it: the line names the pressure and the fold is what answers it, so the model is
 * told and then helped rather than quietly edited. Below the line nothing happens at
 * all — a small Σ is left exactly as the model wrote it.
 *
 * @returns what the fold did, or `undefined` when it did nothing.
 */
async function condensePast(
  record: StateRecord,
  config: ResolvedConfig | undefined,
): Promise<CondenseReport | undefined> {
  if (config === undefined || config.sigmaCondenseChars <= 0 || config.sigmaWarnTokens <= 0) return undefined
  const state = record.get()
  if (estimateTokens(render(state)) < config.sigmaWarnTokens) return undefined
  const findings = state["findings"]
  if (!isPlainObject(findings)) return undefined
  const folded = condense(findings, record.archive(), { maxChars: config.sigmaCondenseChars })
  if (folded.report.folded === 0 && folded.report.superseded === 0) return undefined
  await record.fold({ ...state, findings: folded.findings }, folded.archive)
  return folded.report
}

/**
 * Run one `skill_state` write: parse, validate, merge, persist, acknowledge.
 *
 * The order is the whole contract. A malformed patch never reaches Σ — it is refused
 * before `stateStore` is even consulted. The step is part of the patch rather than a side
 * channel, so it merges, it can be deleted, and it shows up in what changed. And the
 * write is synchronous around the merge: load, merge, persist, so what the ack reports is
 * what the store holds.
 *
 * @param input - what the model sent, plus the session it sent it from.
 * @param options - the durable store, when the host has one; the resolved configuration,
 *   when the host's config says how large a Σ may grow before it is folded.
 */
export async function writeSkillState(
  input: SkillStateWrite,
  options: { readonly storage?: StorageDomain; readonly config?: ResolvedConfig } = {},
): Promise<SkillStateOutcome> {
  const storage = options.storage
  const config = options.config
  const sessionID = input.sessionID
  if (sessionID === undefined || sessionID.length === 0) {
    return {
      text: "skill_state needs a session: it records the state of the conversation it is called from.",
      output: { kind: "error" },
    }
  }
  const parsed = parsePatch(input.state_patch)
  if (parsed.error !== undefined) {
    return { text: parsed.error, output: { kind: "error" } }
  }
  const wanted = input.step
  if (wanted !== undefined && wanted !== null && !Number.isInteger(wanted)) {
    return { text: "step must be an integer, or left out entirely.", output: { kind: "error" } }
  }
  if (input.summary !== undefined && typeof input.summary !== "string") {
    return { text: "summary must be one line of text.", output: { kind: "error" } }
  }

  const record = await stateStore(sessionID, { storage })
  // The step is part of the patch, not a side channel: it is a key of Σ like any other,
  // so it merges, it can be deleted, and it shows up in what changed. A write with no
  // `step` advances whatever Σ already carries — a seed or an earlier write.
  const step = wanted === undefined || wanted === null ? record.step() + 1 : (wanted as number)
  const written: Record<string, unknown> = parsed.patch === undefined ? {} : { ...parsed.patch }
  written["step"] = step
  const dropped = parsed.patch === undefined ? [] : unknownKeys(parsed.patch)

  const changed = await record.apply(written)
  if (typeof input.summary === "string") await record.setSummary(input.summary)

  // Σ only grows, and every character of it is charged to every request. The fold runs
  // here — inside the write, after the merge, on the state the merge produced — because
  // this is the one moment the runtime holds the whole of Σ and a reason to look at its
  // size. Nothing folded means nothing written: `condensePast` returns without touching
  // the record, so an untouched write costs exactly what it always did.
  const condensed = await condensePast(record, config)

  const output: Record<string, unknown> = {
    kind: "state",
    step,
    changed,
    dropped,
    keys: [...STATE_KEYS],
    // `summary` is `string | undefined`, and an `undefined` leaf is not JSON: the host
    // rejects the whole result with "Tool returned a non-JSON value for its output
    // schema" — after `record.apply` has already persisted the write, so the model is
    // told a write failed that in fact landed. `null` keeps the key present, so a reader
    // can still tell "no summary yet" from "no summary at all".
    summary: record.summary() ?? null,
    tokens: estimateTokens(render(record.get())),
  }
  // The fold is reported rather than silent: the render carries a marker where the text
  // was, and this is the machine-readable half of the same statement.
  if (condensed !== undefined) output["condensed"] = condensed
  return { text: ackText({ step, changed, dropped, fromString: parsed.fromString }), output }
}
